const baseDir = path.join(__dirname, '..', 'server', 'src', 'words');

const hiPacksDir = path.join(baseDir, 'hi', 'packs');
const hinglishPacksDir = path.join(baseDir, 'hinglish', 'packs');

fs.mkdirSync(hiPacksDir, { recursive: true });
fs.mkdirSync(hinglishPacksDir, { recursive: true });

const hiMasterEasy = [];
const hiMasterMed = [];
const hiMasterHard = [];

const hinglishMasterEasy = [];
const hinglishMasterMed = [];
const hinglishMasterHard = [];

for (const [packName, items] of Object.entries(rawPacks)) {
    const hiPack = [];
    const hinglishPack = [];

    items.forEach((item, idx) => {
        const [hinglishWord, devWord, extraAliases] = item;

        // Clean & combined aliases
        const allAliases = Array.from(new Set([
            hinglishWord.toLowerCase().trim(),
            devWord.trim(),
            ...(extraAliases || []).map(a => a.toLowerCase().trim())
        ])).filter(Boolean);

        // Hindi version: word is devWord, aliases includes all
        const hiItem = {
            word: devWord.trim(),
            aliases: allAliases
        };
        hiPack.push(hiItem);

        // Hinglish version: word is hinglishWord, aliases includes all
        const hinglishItem = {
            word: hinglishWord.toLowerCase().trim(),
            aliases: allAliases
        };
        hinglishPack.push(hinglishItem);

        // Distribute into easy, medium, hard based on index / length
        if (idx % 3 === 0) {
            hiMasterEasy.push(hiItem);
            hinglishMasterEasy.push(hinglishItem);
        } else if (idx % 3 === 1) {
            hiMasterMed.push(hiItem);
            hinglishMasterMed.push(hinglishItem);
        } else {
            hiMasterHard.push(hiItem);
            hinglishMasterHard.push(hinglishItem);
        }
    });

    // Write individual pack files
    fs.writeFileSync(path.join(hiPacksDir, `${packName}.json`), JSON.stringify(hiPack, null, 2), 'utf8');
    fs.writeFileSync(path.join(hinglishPacksDir, `${packName}.json`), JSON.stringify(hinglishPack, null, 2), 'utf8');
    console.log(`Wrote pack ${packName}: ${items.length} words to hi and hinglish`);
}

